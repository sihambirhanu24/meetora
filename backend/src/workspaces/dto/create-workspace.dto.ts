import { IsString, IsNotEmpty, IsOptional, MaxLength, Matches, IsBoolean } from 'class-validator';

export class CreateWorkspaceDto {
  @IsString()
  @IsNotEmpty()
  @MaxLength(100)
  name: string;

  @IsString()
  @IsOptional()
  @MaxLength(500)
  description?: string;

  @IsString()
  @IsOptional()
  @Matches(/^[a-z0-9-]+$/, {
    message: 'Slug must contain only lowercase letters, numbers, and hyphens',
  })
  @MaxLength(100)
  slug?: string;

  @IsBoolean()
  @IsOptional()
  isPublic?: boolean;
}
